import { type RecoveryOperationId } from '../../application/recovery/recovery.ports';
import { type RecoveryShapeName } from './recovery-shapes';

/** Service gRPC de recovery appelé par une route. */
export type RecoveryClientName = 'creditor' | 'debtor' | 'partner' | 'admin';

/**
 * Traduction d'une route du recouvrement vers son appel gRPC :
 * - `path` : paramètre du chemin → champ de la demande ;
 * - `query` : paramètre de requête → champ (`filter.`, `page.` : sous-message ; `[]` : liste) ;
 * - `body` : corps étalé dans la demande (`spread`) ou rangé dans un champ (`input`…) ;
 * - `unwrap` : champ de la réponse rendu (`settingsView` : réglages et leur dernière modification),
 *   sinon la réponse entière ; `shape` : forme du contrat ; `idempotent` : lecture rejouable ;
 * - `withoutInternalEntries` : journal vu hors du back-office, notes internes retirées par la
 *   gateway même si recovery en rendait (défense en profondeur, R-PR-08).
 */
export interface RecoveryOperation {
  client: RecoveryClientName;
  method: string;
  path?: Record<string, string>;
  query?: Record<string, string>;
  body?: 'spread' | 'input' | 'settings' | 'preferences';
  idempotencyKey?: boolean;
  unwrap?: string;
  shape: RecoveryShapeName;
  idempotent?: boolean;
  withoutInternalEntries?: boolean;
}

